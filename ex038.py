numero1 = int(input('\nDigite um numero inteiro: '))
numero2 = int(input('\nDigite um numero inteiro: '))

if numero1 > numero2:
    print('\nO primeiro valor é maior\n')
elif numero1 < numero2:
    print('\nO segundo valor é maior\n')
else:
    print('\nNao existe valor maior, os dois sao iguais\n')
